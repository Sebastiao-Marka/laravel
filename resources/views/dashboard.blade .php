Empresas de outros paises chegam e ocupam espaços que deveriam ser nosso , dos brasileiros.

Por isso eu percebi a nescecidade de criar um aplicativo que fosse facil de usar e que fosse 
acessivel para todos os empreendedores  .
Seja o pequeno agricultor familiar que produz seus alfaces, seja um dono de barraca de feira, seja um 
lojista de modas, ou mesmo uma empresa de crros de luxo, e tambem para prestadores de serviços autonomos ou
empresas que tambem prestam serviços.

O zabe atente exatamente esses empreendedores mostrando seus produtos e serviços para quem precisa na hora que precisa, 
Como funciona: 
    O dono da loja cria sua loja no aplicativo zabe e sua loja passa a ser exibida no aplicativo para para seus 
clientes priorizando a proximidade, sera exibido endereço que ao clicar ele será direcionado para o GPS, e será exibido o 
contato de whatsapp facilitando a negociação 1 a 1 .  
    Para o prestador de serviço  funciona um pouco direfente,o profissional individual  cria sua conta, e quando o cliente que 
    deseja a realização do serviço, posta o serviço com imagens , videos, descrição, endereço e profissão requerida para a execução,
    se a profissão desejada e a profissão requerida dé match então será exibido aquele serviço para os profissionais mais proximos e 
    a cada hora será dobrada a distancia a fim que de que o  serviço seja exibido para mais profissionais e então seja realizado o quanto antes.
    
    Para o usuario que precisa da empresas prestadoras de serviços, será exibida uma lista de banners com  endereço, descrição de suas
    atividades com imagens, demonstração com videos e contato facilitando tambem a negociação 1 a 1 .
Assim democratizamos a acessibilidade para todos os empreendedores brasileiros e facilitamos a acesso para os usuarios que precisam 
dos produtos e serviços. 

